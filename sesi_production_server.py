def generate_fastapi_app(out_dir: Path) -> Path:
    """Write the FastAPI application file."""
    server_dir = out_dir / "server"
    server_dir.mkdir(parents=True, exist_ok=True)
    path = server_dir / "app.py"
    path.write_text(FASTAPI_APP, encoding="utf-8")
    logger.info("FastAPI app written → %s", path)
    return path


def generate_grafana_dashboard(out_dir: Path) -> Path:
    """Write the Grafana dashboard JSON."""
    mon_dir = out_dir / "monitoring"
    mon_dir.mkdir(parents=True, exist_ok=True)
    path = mon_dir / "dashboard.json"
    path.write_text(
        json.dumps(_grafana_dashboard(), indent=2), encoding="utf-8",
    )
    logger.info("Grafana dashboard written → %s", path)
    return path


def generate_helm_chart(out_dir: Path) -> Path:
    """Write the complete Helm chart directory."""
    chart = out_dir / "helm" / "sesi-oversight"
    templates = chart / "templates"
    templates.mkdir(parents=True, exist_ok=True)

    files: Dict[str, str] = {
        "Chart.yaml": HELM_CHART_YAML,
        "values.yaml": HELM_VALUES_YAML,
        "templates/_helpers.tpl": HELM_HELPERS,
        "templates/deployment.yaml": HELM_DEPLOYMENT,
        "templates/service.yaml": HELM_SERVICE,
        "templates/ingress.yaml": HELM_INGRESS,
        "templates/hpa.yaml": HELM_HPA,
        "templates/pdb.yaml": HELM_PDB,
        "templates/servicemonitor.yaml": HELM_SERVICEMONITOR,
    }

    for rel, content in files.items():
        p = chart / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        logger.info("Helm file written → %s", p)

    # .helmignore
    (chart / ".helmignore").write_text(
        ".git\n*.tgz\n__pycache__\n", encoding="utf-8",
    )
    return chart


def generate_all(base_dir: str = "./sesi_production") -> Dict[str, str]:
    """Generate every artifact under *base_dir*."""
    out = Path(base_dir)
    out.mkdir(parents=True, exist_ok=True)
    return {
        "fastapi": str(generate_fastapi_app(out)),
        "grafana": str(generate_grafana_dashboard(out)),
        "helm": str(generate_helm_chart(out)),
    }


# ═══════════════════════════════════════════════════════════════════════
