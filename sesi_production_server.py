# ═══════════════════════════════════════════════════════════════════════

def _cli():
    logging.basicConfig(level=logging.INFO,
                        format="%(levelname)s  %(message)s")
    cmd = sys.argv[1] if len(sys.argv) > 1 else "generate"

    if cmd == "generate":
        paths = generate_all()
        print("\n── Generated artifacts ──")
        for k, v in paths.items():
            print(f"  {k:10s} → {v}")
        print("\nNext steps:")
        print("  1. pip install fastapi uvicorn prometheus-client")
        print("  2. cd sesi_production/server && uvicorn app:app --reload")
        print("  3. Import monitoring/dashboard.json into Grafana")
        print("  4. helm lint sesi_production/helm/sesi-oversight")
        print("  5. helm install sesi ./helm/sesi-oversight -n sesi --create-namespace")

    elif cmd == "serve":
        # Quick local dev server (no Helm / K8s needed)
        try:
            import uvicorn
        except ImportError:
            print("uvicorn not installed — pip install uvicorn")
            sys.exit(1)
        # Write app.py to a temp location and run it
        tmp = Path("./_sesi_dev_server")
        tmp.mkdir(exist_ok=True)
        app_path = tmp / "app.py"
        app_path.write_text(FASTAPI_APP, encoding="utf-8")
        uvicorn.run(
            "app:app", app_dir=str(tmp),
            host="127.0.0.1", port=8080, reload=True,
        )

    elif cmd == "helm-lint":
        import subprocess
        chart = Path("./sesi_production/helm/sesi-oversight")
        if not chart.exists():
            print("Chart not found. Run `generate` first.")
            sys.exit(1)
        subprocess.run(["helm", "lint", str(chart)], check=False)

    else:
        print(f"Unknown command: {cmd}")
        print("Usage: python ses_production_server.py [generate|serve|helm-lint]")
        sys.exit(1)


if __name__ == "__main__":
    _cli()
