@app.websocket("/ws/alerts")
async def ws_alerts(websocket: WebSocket):
    """
    Real-time alert stream.

    Clients connect and receive JSON messages whenever the framework
    raises an alert (kill-switch, ethical violation, high risk, etc.).
    """
    await websocket.accept()
    _ws_clients.add(websocket)
    logger.info("WS client connected (%d total)", len(_ws_clients))
    try:
        while True:
            # Keep-alive; real alerts are pushed by broadcast_alert()
            await websocket.receive_text()
    except WebSocketDisconnect:
        _ws_clients.discard(websocket)
        logger.info("WS client disconnected (%d remaining)", len(_ws_clients))


async def broadcast_alert(level: str, source: str, message: str):
    """Push an alert to every connected WebSocket client."""
    payload = json.dumps({
        "alert_id": uuid.uuid4().hex[:8],
        "level": level,
        "source": source,
        "message": message,
        "timestamp": time.time(),
    })
    dead = set()
    for ws in _ws_clients:
        try:
            await ws.send_text(payload)
        except Exception:
            dead.add(ws)
    _ws_clients.difference_update(dead)
    if HAS_PROM:
        ACTIVE_ALERTS.set(len(_ws_clients))


